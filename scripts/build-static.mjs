import { readFile, readdir, mkdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import matter from "gray-matter";
import { marked } from "marked";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const postsDirectory = path.join(root, "content", "posts");
const outputDirectories = [path.join(root, "public")];
const defaultSiteUrl = "https://juice-notes.yellow-coin-6347.chatgpt.site";
const siteUrl = (process.env.SITE_URL || defaultSiteUrl).replace(/\/+$/, "");

const escapeHtml = (value = "") =>
  String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");

const requiredFields = [
  "title",
  "slug",
  "publishedAt",
  "date",
  "category",
  "excerpt",
  "readTime",
];

async function loadPosts() {
  const files = (await readdir(postsDirectory))
    .filter((file) => file.endsWith(".md"))
    .sort();

  const posts = await Promise.all(
    files.map(async (file) => {
      const source = await readFile(path.join(postsDirectory, file), "utf8");
      const { data, content } = matter(source);
      const missing = requiredFields.filter((field) => !data[field]);

      if (missing.length > 0) {
        throw new Error(`${file} 缺少字段：${missing.join("、")}`);
      }

      if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(data.slug)) {
        throw new Error(`${file} 的 slug 只能包含小写字母、数字和连字符`);
      }

      return {
        ...data,
        sourceFile: file,
        html: await marked.parse(content, { gfm: true }),
      };
    }),
  );

  const slugs = new Set();
  for (const post of posts) {
    if (slugs.has(post.slug)) {
      throw new Error(`发现重复 slug：${post.slug}`);
    }
    slugs.add(post.slug);
  }

  return posts.sort((a, b) => b.publishedAt.localeCompare(a.publishedAt));
}

