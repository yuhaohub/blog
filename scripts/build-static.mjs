async function writeGenerated(relativePath, content) {
  await Promise.all(
    outputDirectories.map(async (directory) => {
      const destination = path.join(directory, relativePath);
      await mkdir(path.dirname(destination), { recursive: true });
      await writeFile(destination, content, "utf8");
    }),
  );
}

async function build() {
  const posts = await loadPosts();
  const css = await readFile(path.join(root, "app", "globals.css"), "utf8");

  for (const directory of outputDirectories) {
    await rm(path.join(directory, "articles"), { recursive: true, force: true });
    await rm(path.join(directory, "about"), { recursive: true, force: true });
  }

  await writeGenerated("assets/styles.css", css);
  await writeGenerated("index.html", homePage(posts));
  await writeGenerated("articles/index.html", articlesPage(posts));
  await writeGenerated("about/index.html", aboutPage());
  await Promise.all(
    posts.map((post) =>
      writeGenerated(`articles/${post.slug}.html`, postPage(post)),
    ),
  );

  console.log(`Generated ${posts.length + 3} HTML pages from ${posts.length} Markdown posts.`);
}

await build();
